#include <stdio.h>

int main() {
    int i, j, k, m;
    for (i = 0; i < 3; i++) {
        printf("i=%d\n", i);
    }
    j = 0;
    while (j < 3) {
        printf("j=%d\n", j);
         j++;
         }
    for (k = 0; k < 3; k++) {
        printf("k=%d\n", k);
    }
    for (m = 0; m < 3; m++) {
        printf("m=%d\n", m);
    }
    return 0;
}
